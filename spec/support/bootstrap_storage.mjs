import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const nodes=new Map();
const element=id=>{if(!nodes.has(id))nodes.set(id,{hidden:false,disabled:false,textContent:'',title:'',style:{},dataset:{},attributes:{},focus(){},setAttribute(name,value){this.attributes[name]=value;}});return nodes.get(id);};
const choices=[element('new-choice'),element('existing-choice')];
const messages=[];
const context=vm.createContext({document:{getElementById:element,querySelector:s=>s==='#storage button'?choices[0]:null,querySelectorAll:s=>s==='#storage .setup-choice'?choices:[...nodes.values()]},window:{webkit:{messageHandlers:{browser:{postMessage:m=>messages.push(JSON.parse(JSON.stringify(m)))}}}}});
const source=fs.readFileSync(new URL('../../app/shell/bootstrap.html',import.meta.url),'utf8');
const scripts=[...source.matchAll(/<script>([\s\S]*?)<\/script>/g)];
vm.runInContext(scripts.at(-1)[1],context);
context.storageScreen();messages.length=0;
context.selectStorage('existing');
assert.equal(messages.at(-1)?.storage,'pick','Selecting another folder must open the picker on the first click');
context.selectStorage('existing');context.continueSetup();
assert.equal(messages.length,1,'Clicks while the picker is open must not start another picker or backend');
context.storagePicked(null);
assert.equal(choices[0].attributes['aria-pressed'],'true','Cancelling the first picker retains Start fresh');
assert.equal(element('get-started').disabled,false);
context.selectStorage('existing');
context.storagePicked('/Users/admin/Existing/data');
assert.equal(element('get-started').disabled,false);
assert.equal(choices[1].attributes['aria-pressed'],'true');
assert.equal(element('storage-directory').textContent,'…/Existing/data');
context.welcomeScreen();context.continueSetup();
assert.equal(element('storage-directory').textContent,'…/Existing/data','Back must preserve the chosen path');
messages.length=0;
context.pickStorage();context.storagePicked(null);
assert.equal(element('storage-directory').textContent,'…/Existing/data','Cancelling a replacement must retain the prior path');
context.continueSetup();context.continueSetup();
assert.equal(messages.filter(m=>m.storage==='existing').length,1,'Continue applies the selected folder once');
assert.equal(messages.at(-1).directory,'/Users/admin/Existing/data');
console.log('bootstrap storage: immediate picker, retained selection, cancel and repeated-click guards passed');

context.storageError('');context.welcomeScreen();messages.length=0;
context.continueSetup({detail:1});context.continueSetup({detail:2});
assert.equal(messages.filter(m=>m.storage).length,0,'Double click on Welcome must not apply storage on the next screen');
